/**
 * Quick statistics calculator for status badges
 */
export function getAvailabilityStatus(availableLots: number, totalLots: number): 'available' | 'limited' | 'full' {
  if (availableLots === 0) return 'full';
  // If less than 10% or less than 20 lots, treat as limited
  if (availableLots <= 20 || availableLots / totalLots < 0.12) return 'limited';
  return 'available';
}
